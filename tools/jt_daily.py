# 自動羅馬拼音（romaji.py）分詞錯的地方
ROFIX = [('Keiseiue no','Keisei Ueno'),('Yoko wa made','Yokohama de'),('Chiekkuin','Chekkuin'),('chiekkuin','chekkuin'),('Wan・tsunhan','Wan Tsunhan'),
 ('A to,','Ato,'),('A to ','Ato '),('a to ','ato '),('omachikudasai','omachi kudasai'),('Onomi mono','Onomimono'),('ika ga','ikaga'),('sonoma made','sono mama de'),
 ('kādoka denshi manēnomi','kādo ka denshi manē nomi'),('Atatamemashōka','Atatamemashō ka'),('ōkagai','oukagai'),('kippūriba','kippu uriba'),
 ('Ue no de hibiyasen','Ueno de Hibiya-sen'),('Higashiginza','Higashi-Ginza'),('Waifuai','Waifai'),('jieiāru','jeiāru')]
def rj(kana, _r=None):
    from romaji import romaji
    r = romaji(kana)
    for a, b in ROFIX: r = r.replace(a, b)
    return r
