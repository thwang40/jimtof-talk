def qphoto(q, C):
    """整句截圖用的照片：q['photo']，或這句單字框最多的那張（C＝CROPS_D[day]['crops']）"""
    bx = [C[w] for w in q['w'] if w in C and 'fallback' not in C[w][2:]]
    if q.get('photo') or not bx: return q.get('photo')
    return max({b[0] for b in bx}, key=lambda x: sum(b[0] == x for b in bx))
